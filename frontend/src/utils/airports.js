// Dynamic client cache for any airport fetched from the 7,800+ global database
const DYNAMIC_CACHE = new Map();

export function registerAirport(airport) {
  if (airport && airport.code) {
    DYNAMIC_CACHE.set(airport.code.toUpperCase(), airport);
  }
}

export function getAirportInfo(code) {
  if (!code) return null;
  const upper = code.trim().toUpperCase();
  if (DYNAMIC_CACHE.has(upper)) {
    return DYNAMIC_CACHE.get(upper);
  }
  if (AIRPORTS_MAP[upper]) {
    return AIRPORTS_MAP[upper];
  }
  return {
    code: upper,
    city: upper,
    country: '',
    name: `Aeropuerto ${upper}`
  };
}
